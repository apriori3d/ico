"""``ico assets lock``: sizes and sha256 of every file, from the sources'
metadata (LFS files are not downloaded; small git files are fetched and
hashed), written to ``assets.lock``."""

from __future__ import annotations

import fnmatch
import hashlib
import os
from pathlib import Path, PurePosixPath

from ico.assets.hub import check_online, hf_files, hf_url, open_url, remote_size
from ico.assets.manifest import AssetFile, AssetLock, AssetSpec, Manifest, ManifestError

CHUNK = 1 << 20


def lock(manifest: Manifest, ids: list[str] | None = None) -> dict[str, AssetLock]:
    """Lock the given assets (all by default) and write ``assets.lock``,
    keeping the entries of the others; returns the new entries.

    Raises:
        HubError: Offline, or a source failed.
        ManifestError: An unknown id, or a file / pattern that the
            repository does not have at that revision.
    """
    check_online("ico assets lock")
    chosen = ids if ids else sorted(manifest.assets)
    unknown = [i for i in chosen if i not in manifest.assets]
    if unknown:
        raise ManifestError(f"unknown asset(s): {', '.join(unknown)}")
    new = {id: lock_one(manifest.assets[id]) for id in chosen}
    write_lock(manifest.path.with_name("assets.lock"), {**manifest.locks, **new})
    return new


def lock_one(spec: AssetSpec) -> AssetLock:
    if spec.url is not None:
        assert spec.sha256 is not None
        name = PurePosixPath(spec.path).name
        return AssetLock(
            spec.id, "file", (AssetFile(name, remote_size(spec.url), spec.sha256),)
        )
    hf = spec.hf
    assert hf is not None
    token = os.environ.get(hf.token_env) if hf.token_env else None
    remote = hf_files(hf.repo, hf.revision, token)
    if hf.file is not None:
        chosen = [f for f in remote if f.name == hf.file]
        if not chosen:
            raise ManifestError(
                f"{spec.id!r}: {hf.repo}@{hf.revision[:8]} has no {hf.file!r}"
            )
    else:
        chosen = [
            f for f in remote if any(fnmatch.fnmatch(f.name, p) for p in hf.include)
        ]
        empty = [
            p for p in hf.include if not any(fnmatch.fnmatch(f.name, p) for f in remote)
        ]
        if empty:
            raise ManifestError(
                f"{spec.id!r}: {hf.repo}@{hf.revision[:8]} has nothing for {', '.join(empty)}"
            )
    files: list[AssetFile] = []
    for f in sorted(chosen, key=lambda f: f.name):
        sha256 = f.sha256 or _hash_url(hf_url(hf.repo, hf.revision, f.name), token)
        name = PurePosixPath(spec.path).name if spec.kind == "file" else f.name
        files.append(AssetFile(name, f.size, sha256))
    return AssetLock(spec.id, spec.kind, tuple(files))


def _hash_url(url: str, token: str | None) -> str:
    digest = hashlib.sha256()
    with open_url(url, token) as response:
        while chunk := response.read(CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def write_lock(path: Path, locks: dict[str, AssetLock]) -> None:
    lines = [
        "# assets.lock — generated by `ico assets lock`, do not edit",
        "version = 1",
    ]
    for id in sorted(locks):
        entry = locks[id]
        lines += [
            "",
            "[[asset]]",
            f"id = {_q(entry.id)}",
            f'kind = "{entry.kind}"',
            "files = [",
        ]
        lines += [
            f'  {{ name = {_q(f.name)}, size = {f.size}, sha256 = "{f.sha256}" }},'
            for f in entry.files
        ]
        lines.append("]")
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    tmp.replace(path)


def _q(text: str) -> str:
    """A TOML basic string."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
