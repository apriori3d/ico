"""``assets.toml`` and ``assets.lock``: reading and validation.

``assets.toml`` (written by people)::

    version = 1

    [assets.wan22-i2v-high]
    description = "Wan2.2 I2V A14B, high-noise expert, fp16"
    license = "apache-2.0"
    hf = { repo = "Comfy-Org/Wan_2.2_ComfyUI_Repackaged",
           revision = "ee6f4a40737a995bf5818954cfce6d59443b0f04",
           file = "split_files/diffusion_models/wan2.2_i2v_high_noise_14B_fp16.safetensors" }
    path = "wan22/high_noise_14B_fp16.safetensors"

    [assets.propainter]
    url = "https://github.com/sczhou/ProPainter/releases/download/v0.1.0/ProPainter.pth"
    sha256 = "12c070c4..."

An asset has one source: ``hf`` with ``file`` (one file) or ``include``
(glob patterns: a tree), at a commit ``revision``; or ``url`` with its
``sha256``. ``path`` is where it lives under the asset root: by default
``<id>/<file name>`` for a file and ``<id>`` for a tree.

``assets.lock`` (generated by ``ico assets lock``)::

    version = 1

    [[asset]]
    id = "wan22-i2v-high"
    kind = "file"
    files = [ { name = "high_noise_14B_fp16.safetensors", size = 28577914792,
                sha256 = "c21c21ef..." } ]

File names are relative to the directory of the asset's path (a file
asset has one file: its own name).
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Literal, cast

if sys.version_info >= (3, 11):
    import tomllib
else:  # pragma: no cover
    import tomli as tomllib

VERSION = 1
ID = re.compile(r"^[a-z0-9][a-z0-9._-]*$")
SHA1 = re.compile(r"^[0-9a-f]{40}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")

Kind = Literal["file", "tree"]


class ManifestError(ValueError):
    """A malformed ``assets.toml`` or ``assets.lock``; the message names
    the file and the asset."""


@dataclass(frozen=True)
class HfSource:
    """A file or a subset of a Hugging Face repository at a commit."""

    repo: str
    revision: str
    file: str | None = None
    include: tuple[str, ...] = ()
    token_env: str | None = None


@dataclass(frozen=True)
class AssetSpec:
    """One entry of ``assets.toml``."""

    id: str
    path: str
    kind: Kind
    hf: HfSource | None = None
    url: str | None = None
    sha256: str | None = None
    description: str = ""
    license: str = ""


@dataclass(frozen=True)
class AssetFile:
    name: str
    size: int
    sha256: str


@dataclass(frozen=True)
class AssetLock:
    """One entry of ``assets.lock``."""

    id: str
    kind: Kind
    files: tuple[AssetFile, ...]

    @property
    def size(self) -> int:
        return sum(f.size for f in self.files)


@dataclass(frozen=True)
class Manifest:
    """``assets.toml`` and, when present, its ``assets.lock``."""

    path: Path
    assets: dict[str, AssetSpec]
    locks: dict[str, AssetLock]


def load_manifest(path: Path) -> Manifest:
    """Read ``assets.toml`` at ``path`` and the ``assets.lock`` beside it
    (missing: no locks).

    Raises:
        ManifestError: Unknown keys, a bad id, a branch as ``revision``,
            no source or two, ``url`` without ``sha256``, a lock entry of
            an unknown asset or of another kind.
    """
    data = _read(path)
    _keys(data, {"version", "assets"}, path.name)
    _version(data, path.name)
    raw = data.get("assets", {})
    if not isinstance(raw, dict):
        raise ManifestError(f"{path.name}: [assets] must be a table")
    assets = {
        id: _spec(id, entry, path.name)
        for id, entry in cast(dict[str, object], raw).items()
    }
    lock_path = path.with_name("assets.lock")
    locks = load_lock(lock_path) if lock_path.is_file() else {}
    for id, lock in locks.items():
        spec = assets.get(id)
        if spec is None:
            raise ManifestError(f"assets.lock: {id!r} is not in {path.name}")
        if spec.kind != lock.kind:
            raise ManifestError(
                f"assets.lock: {id!r} is a {lock.kind}, {path.name} makes it a "
                f"{spec.kind}: run `ico assets lock {id}`"
            )
    return Manifest(path=path, assets=assets, locks=locks)


def load_lock(path: Path) -> dict[str, AssetLock]:
    """Read ``assets.lock``."""
    data = _read(path)
    _keys(data, {"version", "asset"}, path.name)
    _version(data, path.name)
    locks: dict[str, AssetLock] = {}
    for entry in _list(data.get("asset", []), f"{path.name}: [[asset]]"):
        where = f"{path.name}: [[asset]]"
        table = _table(entry, where)
        _keys(table, {"id", "kind", "files"}, where)
        id = _req(table, "id", where)
        where = f"{path.name}: {id!r}"
        kind = _kind(table.get("kind"), where)
        files = tuple(
            _file(f, where) for f in _list(table.get("files", []), f"{where} files")
        )
        if kind == "file" and len(files) != 1:
            raise ManifestError(f"{where}: a file asset has exactly one file")
        locks[id] = AssetLock(id=id, kind=kind, files=files)
    return locks


# ─── Parsing ───


def _read(path: Path) -> dict[str, object]:
    try:
        return cast(dict[str, object], tomllib.loads(path.read_text(encoding="utf-8")))
    except tomllib.TOMLDecodeError as e:
        raise ManifestError(f"{path.name}: {e}") from None


def _spec(id: str, entry: object, file: str) -> AssetSpec:
    where = f"{file}: {id!r}"
    if not ID.match(id):
        raise ManifestError(
            f"{where}: ids are lower case letters, digits, '.', '_' and '-'"
        )
    table = _table(entry, where)
    _keys(table, {"description", "license", "hf", "url", "sha256", "path"}, where)
    hf = _hf(table["hf"], where) if "hf" in table else None
    url = _opt(table, "url", where)
    sha256 = _opt(table, "sha256", where)
    if (hf is None) == (url is None):
        raise ManifestError(f"{where}: give one source, 'hf' or 'url'")
    if url is not None and (sha256 is None or not SHA256.match(sha256)):
        raise ManifestError(f"{where}: a 'url' asset needs its 'sha256' (64 hex)")
    if hf is not None and sha256 is not None:
        raise ManifestError(f"{where}: 'sha256' is for 'url' assets ('hf' is locked)")
    kind: Kind = "tree" if hf is not None and hf.include else "file"
    path = _opt(table, "path", where) or _default_path(id, hf, url)
    _relative(path, where)
    return AssetSpec(
        id=id,
        path=path,
        kind=kind,
        hf=hf,
        url=url,
        sha256=sha256,
        description=_opt(table, "description", where) or "",
        license=_opt(table, "license", where) or "",
    )


def _hf(value: object, where: str) -> HfSource:
    where = f"{where} hf"
    table = _table(value, where)
    _keys(table, {"repo", "revision", "file", "include", "token_env"}, where)
    revision = _req(table, "revision", where)
    if not SHA1.match(revision):
        raise ManifestError(
            f"{where}: 'revision' must be a commit sha (40 hex), not {revision!r}"
        )
    file = _opt(table, "file", where)
    include = tuple(
        _plain(v, f"{where} include") for v in _list(table.get("include", []), where)
    )
    if (file is None) == (not include):
        raise ManifestError(f"{where}: give 'file' (one file) or 'include' (a tree)")
    return HfSource(
        repo=_req(table, "repo", where),
        revision=revision,
        file=file,
        include=include,
        token_env=_opt(table, "token_env", where),
    )


def _default_path(id: str, hf: HfSource | None, url: str | None) -> str:
    if hf is not None and hf.include:
        return id
    name = PurePosixPath(hf.file if hf is not None and hf.file else str(url)).name
    return f"{id}/{name.split('?')[0]}"


def _file(value: object, where: str) -> AssetFile:
    table = _table(value, f"{where} files")
    _keys(table, {"name", "size", "sha256"}, f"{where} files")
    name = _req(table, "name", where)
    _relative(name, where)
    size = table.get("size")
    sha256 = _req(table, "sha256", where)
    if not isinstance(size, int) or isinstance(size, bool) or size < 0:
        raise ManifestError(f"{where}: {name!r} needs a 'size' in bytes")
    if not SHA256.match(sha256):
        raise ManifestError(f"{where}: {name!r} has a bad 'sha256'")
    return AssetFile(name=name, size=size, sha256=sha256)


def _relative(path: str, where: str) -> None:
    parts = PurePosixPath(path).parts
    if not parts or path.startswith("/") or ".." in parts:
        raise ManifestError(
            f"{where}: {path!r} must be a relative path inside the root"
        )


def _kind(value: object, where: str) -> Kind:
    if value == "file":
        return "file"
    if value == "tree":
        return "tree"
    raise ManifestError(f"{where}: 'kind' is 'file' or 'tree'")


def _version(data: dict[str, object], file: str) -> None:
    if data.get("version", VERSION) != VERSION:
        raise ManifestError(f"{file}: unsupported version {data.get('version')!r}")


def _keys(table: dict[str, object], allowed: set[str], where: str) -> None:
    unknown = sorted(set(table) - allowed)
    if unknown:
        raise ManifestError(
            f"{where}: unknown key(s) {', '.join(unknown)}; "
            f"allowed: {', '.join(sorted(allowed))}"
        )


def _table(value: object, where: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise ManifestError(f"{where} must be a table")
    return cast(dict[str, object], value)


def _list(value: object, where: str) -> list[object]:
    if not isinstance(value, list):
        raise ManifestError(f"{where} must be a list")
    return cast(list[object], value)


def _plain(value: object, where: str) -> str:
    if not isinstance(value, str) or not value:
        raise ManifestError(f"{where}: expected a non-empty string")
    return value


def _opt(table: dict[str, object], key: str, where: str) -> str | None:
    return _req(table, key, where) if table.get(key) is not None else None


def _req(table: dict[str, object], key: str, where: str) -> str:
    value = table.get(key)
    if not isinstance(value, str) or not value:
        raise ManifestError(f"{where}: '{key}' must be a non-empty string")
    return value
